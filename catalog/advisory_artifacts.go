package catalog

import "maps"

// BuiltInEndpointOverlayArtifacts returns the checked-in endpoint overlay
// registrations. Paths are relative to the catalog artifact root. The list
// contains metadata only and requires no local artifact or cache access.
func BuiltInEndpointOverlayArtifacts() []CatalogSpecArtifact {
	rows := make([]CatalogSpecArtifact, 0, len(endpointOverlayArtifacts))
	for _, overlay := range endpointOverlayArtifacts {
		overlay.SpecRefID = overlay.Metadata["spec_ref_id"]
		if overlay.SpecRefID == "" {
			overlay.SpecRefID = overlay.ArtifactID
		}
		overlay.Kind = "advisory-overlay"
		overlay.OverlayPath = overlay.Path
		metadata := map[string]string{"official_openapi": "false", "derived_from_docs": "true"}
		maps.Copy(metadata, overlay.Metadata)
		overlay.Metadata = metadata
		rows = append(rows, overlay)
	}
	return rows
}

